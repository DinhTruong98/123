"""Export the watch icons for firmware (WP6).

From the same PNGs the simulator uses (assets/icons, white on transparent) write
`icons.h` with, per icon:
  (a) `<name>_xbm`    1-bit 48×48 bitmap in XBM layout for U8g2 `drawXBMP()`:
      rows top to bottom, each row padded to whole bytes (48 px -> 6 bytes), bit 0 (LSB) of a
      byte = leftmost pixel, 1 = pixel on. 6 × 48 = 288 bytes.
  (b) `<name>_rgb565` 96×96 RGB565 image, white icon alpha-blended on black, stored as a
      **byte** array in big-endian order (high byte first per pixel), i.e. exactly the byte
      stream a GC9A01 expects on SPI. 2 × 96 × 96 = 18432 bytes. With TFT_eSPI:
          tft.setSwapBytes(false);  // data is already MSB-first in memory
          tft.pushImage(x, y, 96, 96, (const uint16_t *)SW_ICONS[id].rgb565);
      (If you convert it to a native uint16_t array on a little-endian MCU, use setSwapBytes(true).)
plus a lookup table `SW_ICONS[SW_NUM_CLASSES]` indexed by class id in config order, and
`icons_preview.png` (1-bit and RGB565 versions decoded back from the exported bytes, upscaled).
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

from soundwatch import paths
from soundwatch.config import Config, load_config

XBM_SIZE = 48
RGB_SIZE = 96


def load_alpha(path: Path, size: int) -> np.ndarray:
    """Icon coverage (alpha) resized to size×size, float in [0, 1]."""
    im = Image.open(path).convert("RGBA")
    a = im.getchannel("A")
    if a.getextrema() == (255, 255):  # no transparency: use inverted luminance (black icon on white)
        a = Image.eval(im.convert("L"), lambda v: 255 - v)
    a = a.resize((size, size), Image.Resampling.LANCZOS)
    return np.asarray(a, dtype=np.float32) / 255.0


def to_xbm(alpha: np.ndarray, threshold: float = 0.5) -> bytes:
    """Pack a (h, w) coverage map into XBM bytes (LSB = leftmost pixel, rows padded to bytes)."""
    h, w = alpha.shape
    bits = alpha >= threshold
    row_bytes = (w + 7) // 8
    out = bytearray(h * row_bytes)
    for y in range(h):
        for x in range(w):
            if bits[y, x]:
                out[y * row_bytes + x // 8] |= 1 << (x % 8)
    return bytes(out)


def from_xbm(data: bytes, w: int, h: int) -> np.ndarray:
    row_bytes = (w + 7) // 8
    arr = np.zeros((h, w), dtype=bool)
    for y in range(h):
        for x in range(w):
            arr[y, x] = bool(data[y * row_bytes + x // 8] >> (x % 8) & 1)
    return arr


def to_rgb565_be(alpha: np.ndarray, fg: tuple[int, int, int] = (255, 255, 255),
                 bg: tuple[int, int, int] = (0, 0, 0)) -> bytes:
    """Blend fg over bg by coverage and pack as big-endian RGB565 bytes."""
    a = alpha[..., None]
    rgb = np.asarray(bg, np.float32) * (1 - a) + np.asarray(fg, np.float32) * a
    rgb = np.clip(np.round(rgb), 0, 255).astype(np.uint16)
    v = ((rgb[..., 0] >> 3) << 11) | ((rgb[..., 1] >> 2) << 5) | (rgb[..., 2] >> 3)
    return v.astype(">u2").tobytes()


def from_rgb565_be(data: bytes, w: int, h: int) -> np.ndarray:
    v = np.frombuffer(data, dtype=">u2").reshape(h, w).astype(np.uint32)
    r = (v >> 11) & 0x1F
    g = (v >> 5) & 0x3F
    b = v & 0x1F
    return np.stack([r * 255 // 31, g * 255 // 63, b * 255 // 31], axis=-1).astype(np.uint8)


def _c_array(name: str, data: bytes, per_line: int = 16) -> str:
    # 4-byte aligned so the RGB565 bytes can be passed as (const uint16_t *)
    lines = []
    for i in range(0, len(data), per_line):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + per_line]) + ",")
    return f"static const uint8_t {name}[{len(data)}] SW_ALIGN PROGMEM = {{\n" + "\n".join(lines) + "\n};\n"


def _ident(icon_file: str) -> str:
    stem = Path(icon_file).stem
    return "icon_" + "".join(ch if ch.isalnum() else "_" for ch in stem).lower()


def export_icons(cfg: Config, out_dir: Path, icons_dir: Path | None = None) -> dict[str, Path]:
    icons_dir = icons_dir or paths.ICONS
    out_dir.mkdir(parents=True, exist_ok=True)
    unique: dict[str, tuple[bytes, bytes]] = {}
    for sc in cfg.classes:
        if sc.icon in unique:
            continue
        p = icons_dir / sc.icon
        if not p.exists():
            raise FileNotFoundError(p)
        unique[sc.icon] = (to_xbm(load_alpha(p, XBM_SIZE)), to_rgb565_be(load_alpha(p, RGB_SIZE)))

    h = [
        "// Generated by `python -m soundwatch export-icons` (WP6). Do not edit.",
        "// Source: assets/icons/*.png (Google Material Icons, Apache-2.0, see assets/icons/SOURCES.md).",
        "//",
        f"// *_xbm    : {XBM_SIZE}x{XBM_SIZE} 1-bit, XBM layout for U8g2 drawXBMP(): rows top->bottom,",
        f"//            each row padded to {(XBM_SIZE + 7) // 8} bytes, bit0 (LSB) = leftmost pixel, 1 = on. "
        f"{(XBM_SIZE + 7) // 8 * XBM_SIZE} bytes.",
        "//            u8g2.drawXBMP(x, y, SW_ICON_XBM_W, SW_ICON_XBM_H, SW_ICONS[id].xbm);",
        f"// *_rgb565 : {RGB_SIZE}x{RGB_SIZE} RGB565, white icon on black, BIG-ENDIAN bytes (high byte",
        f"//            first per pixel = SPI wire order of GC9A01). {RGB_SIZE * RGB_SIZE * 2} B. TFT_eSPI:",
        "//              tft.setSwapBytes(false);",
        f"//              tft.pushImage(x, y, {RGB_SIZE}, {RGB_SIZE},",
        "//                            (const uint16_t *)SW_ICONS[id].rgb565);",
        "//            (re-packed as native uint16_t on a little-endian MCU: use setSwapBytes(true)).",
        "#pragma once",
        "#include <stdint.h>",
        "#ifndef PROGMEM",
        "#define PROGMEM",
        "#endif",
        "#ifndef SW_ALIGN",
        "#define SW_ALIGN __attribute__((aligned(4)))",
        "#endif",
        "",
        f"#define SW_ICON_XBM_W {XBM_SIZE}",
        f"#define SW_ICON_XBM_H {XBM_SIZE}",
        f"#define SW_ICON_XBM_BYTES {(XBM_SIZE + 7) // 8 * XBM_SIZE}",
        f"#define SW_ICON_RGB565_W {RGB_SIZE}",
        f"#define SW_ICON_RGB565_H {RGB_SIZE}",
        f"#define SW_ICON_RGB565_BYTES {RGB_SIZE * RGB_SIZE * 2}",
        f"#define SW_NUM_CLASSES {cfg.num_classes}",
        "",
    ]
    for icon, (xbm, rgb) in unique.items():
        ident = _ident(icon)
        h.append(f"// {icon}")
        h.append(_c_array(f"{ident}_xbm", xbm, 12))
        h.append(_c_array(f"{ident}_rgb565", rgb, 16))
    h += [
        "typedef struct {",
        "  const char *key;",
        "  const uint8_t *xbm;     // SW_ICON_XBM_BYTES",
        "  const uint8_t *rgb565;  // SW_ICON_RGB565_BYTES, big-endian",
        "} sw_icon_t;",
        "",
        "// indexed by class id (= model output index, config order)",
        "static const sw_icon_t SW_ICONS[SW_NUM_CLASSES] = {",
    ]
    for sc in cfg.classes:
        ident = _ident(sc.icon)
        h.append(f'  {{"{sc.key}", {ident}_xbm, {ident}_rgb565}},  // {sc.id}: {sc.icon}')
    h += ["};", ""]
    header = out_dir / "icons.h"
    header.write_text("\n".join(h), encoding="utf-8")

    preview = out_dir / "icons_preview.png"
    _preview(cfg, unique, preview)
    return {"header": header, "preview": preview}


def _preview(cfg: Config, unique: dict[str, tuple[bytes, bytes]], path: Path) -> None:
    """Grid: per class, the 1-bit icon (decoded from the exported bytes, ×3) and the RGB565 one."""
    cell_w, cell_h = 170, 270
    n = cfg.num_classes
    img = Image.new("RGB", (cell_w * n + 10, cell_h), (30, 32, 38))
    d = ImageDraw.Draw(img)
    for i, sc in enumerate(cfg.classes):
        xbm, rgb = unique[sc.icon]
        x0 = 10 + i * cell_w
        bits = from_xbm(xbm, XBM_SIZE, XBM_SIZE)
        one = Image.fromarray(np.where(bits, 255, 0).astype(np.uint8), "L").convert("RGB")
        one = one.resize((XBM_SIZE * 3, XBM_SIZE * 3), Image.Resampling.NEAREST)
        img.paste(one, (x0, 10))
        col = Image.fromarray(from_rgb565_be(rgb, RGB_SIZE, RGB_SIZE), "RGB")
        img.paste(col, (x0 + (XBM_SIZE * 3 - RGB_SIZE) // 2, 160))
        d.text((x0, 256 - 2), f"{sc.id}: {sc.key}", fill=(220, 220, 220))
    img.save(path)


def add_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--out", default=None, help=f"output directory (default: {paths.FIRMWARE})")


def main(args: argparse.Namespace) -> int:
    cfg = load_config(getattr(args, "config", None))
    out = Path(args.out) if args.out else paths.FIRMWARE
    res = export_icons(cfg, out)
    print(f"wrote {res['header']}")
    print(f"wrote {res['preview']}")
    return 0
