"""Export golden feature vectors for firmware tests (WP2).

python -m soundwatch export-golden [--out DIR]

Writes to ``artifacts/golden/`` (default):
    case_<k>_<name>/input.wav      16 kHz mono int16 PCM, 16000 samples
    case_<k>_<name>/input_f32.npy  float32 = int16 / 32768 (exact input to compute_logmel)
    case_<k>_<name>/logmel.npy     (49, 40) float32 log-mel, NOT normalized
    golden_features.h              int16 inputs + float log-mel references for all cases
    mel_filterbank.h               feature params, periodic Hann window, sparse mel filterbank
    manifest.json, README.md
"""

from __future__ import annotations

import argparse
import json
import wave
from pathlib import Path

import numpy as np

from soundwatch import paths
from soundwatch.audio import features as F
from soundwatch.config import AudioConfig, load_config


def add_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--out", default=None, help=f"output directory (default: {paths.GOLDEN})")


# ---- deterministic test signals --------------------------------------------------------------
def _quantize(x: np.ndarray) -> np.ndarray:
    return np.clip(np.round(np.asarray(x, np.float64) * 32768.0), -32768, 32767).astype(np.int16)


def make_cases(audio: AudioConfig, windows_dir: Path | None = None) -> list[tuple[str, str, np.ndarray]]:
    """Return [(name, description, int16 (window_samples,))]."""
    sr, n = audio.sample_rate, audio.window_samples
    t = np.arange(n, dtype=np.float64) / sr
    cases: list[tuple[str, str, np.ndarray]] = []
    cases.append(("silence", "all zeros", np.zeros(n, np.int16)))
    sine = _quantize(0.5 * np.sin(2 * np.pi * 1000.0 * t))
    cases.append(("sine_1khz", "1000 Hz sine, amplitude 0.5", sine))
    rng = np.random.default_rng(0)
    cases.append(("white_noise", "uniform white noise in [-0.25, 0.25), numpy default_rng(0)",
                  _quantize(rng.uniform(-0.25, 0.25, n))))
    f0, f1, dur = 100.0, 7000.0, n / sr
    phase = 2 * np.pi * (f0 * t + (f1 - f0) / (2 * dur) * t * t)
    cases.append(("chirp", "linear chirp 100 -> 7000 Hz, amplitude 0.5", _quantize(0.5 * np.sin(phase))))

    windows_dir = paths.WINDOWS if windows_dir is None else windows_dir
    test_npz = windows_dir / "test.npz"
    real = None
    if test_npz.exists():
        try:
            with np.load(test_npz, allow_pickle=False) as z:
                w = np.asarray(z["wave"][0])
            real = _quantize(F._fit_length(F.to_float32(w), n))
        except (KeyError, ValueError, OSError, IndexError):
            real = None
    if real is not None:
        cases.append(("test_window0", "first window of artifacts/data/windows/test.npz", real))
    else:
        x = 0.2 * np.sin(2 * np.pi * 300 * t) + 0.15 * np.sin(2 * np.pi * 1500 * t) \
            + 0.1 * np.sin(2 * np.pi * 4000 * t)
        cases.append(("sum_of_sines", "0.2*sin(300 Hz) + 0.15*sin(1500 Hz) + 0.1*sin(4000 Hz) "
                      "(test.npz not found)", _quantize(x)))
    return cases


# ---- writers ---------------------------------------------------------------------------------
def write_wav(path: Path, x: np.ndarray, sr: int) -> None:
    with wave.open(str(path), "wb") as wf:
        wf.setnchannels(1)
        wf.setsampwidth(2)
        wf.setframerate(sr)
        wf.writeframes(np.asarray(x, "<i2").tobytes())


def read_wav(path: Path) -> tuple[np.ndarray, int]:
    with wave.open(str(path), "rb") as wf:
        assert wf.getnchannels() == 1 and wf.getsampwidth() == 2
        return np.frombuffer(wf.readframes(wf.getnframes()), "<i2").copy(), wf.getframerate()


def _fmt_f(v: float) -> str:
    s = f"{float(v):.9g}"
    if "e" not in s and "." not in s and "inf" not in s and "nan" not in s:
        s += ".0"
    return s + "f"


def _c_array(ctype: str, name: str, values: np.ndarray, per_line: int, fmt) -> str:
    flat = np.asarray(values).ravel()
    dims = "".join(f"[{d}]" for d in np.asarray(values).shape)
    lines = []
    for i in range(0, flat.size, per_line):
        lines.append("    " + ", ".join(fmt(v) for v in flat[i:i + per_line]) + ",")
    return f"static const {ctype} {name}{dims} = {{\n" + "\n".join(lines) + "\n};\n"


def _header(guard: str, body: str, doc: str) -> str:
    return (f"/* {doc}\n * Generated by `python -m soundwatch export-golden` (WP2). Do not edit. */\n"
            f"#ifndef {guard}\n#define {guard}\n\n#include <stdint.h>\n\n{body}\n#endif /* {guard} */\n")


def mel_filterbank_header(audio: AudioConfig) -> str:
    hann = F.hann_window(audio.n_fft)
    fb = F.mel_filterbank(audio.sample_rate, audio.n_fft, audio.n_mels, audio.fmin, audio.fmax)
    start, length, weights = F.mel_filterbank_sparse(fb)
    offset = np.concatenate([[0], np.cumsum(length)[:-1]]).astype(np.int32)
    b = [
        f"#define SW_SAMPLE_RATE {audio.sample_rate}",
        f"#define SW_WINDOW_SAMPLES {audio.window_samples}",
        f"#define SW_N_FFT {audio.n_fft}",
        f"#define SW_N_BINS {audio.n_fft // 2 + 1}",
        f"#define SW_FRAME_STEP {audio.frame_step}",
        f"#define SW_N_FRAMES {audio.n_frames}",
        f"#define SW_N_MELS {audio.n_mels}",
        f"#define SW_FMIN_HZ {_fmt_f(audio.fmin)}",
        f"#define SW_FMAX_HZ {_fmt_f(audio.fmax)}",
        f"#define SW_LOG_EPS {_fmt_f(audio.log_eps)}",
        f"#define SW_MEL_N_WEIGHTS {weights.size}",
        "",
        "/* Periodic Hann: w[n] = 0.5 - 0.5*cos(2*pi*n/N), N = SW_N_FFT (w[0] = 0, w[N/2] = 1). */",
        _c_array("float", "sw_hann_window", hann, 6, _fmt_f),
        "/* HTK-mel triangular filterbank, norm=None (peak 1.0). Band m:",
        " *   mel[m] = sum_{j<len[m]} power[start[m]+j] * weights[offset[m]+j]",
        " * then logmel = logf(mel + SW_LOG_EPS). power[k] = re^2 + im^2 of the unscaled rfft. */",
        _c_array("uint16_t", "sw_mel_start", start, 16, lambda v: str(int(v))),
        _c_array("uint16_t", "sw_mel_len", length, 16, lambda v: str(int(v))),
        _c_array("uint16_t", "sw_mel_offset", offset, 16, lambda v: str(int(v))),
        _c_array("float", "sw_mel_weights", weights, 6, _fmt_f),
    ]
    return _header("SOUNDWATCH_MEL_FILTERBANK_H", "\n".join(b),
                   "SoundWatch log-mel feature constants (plan section 4.2).")


def golden_header(cases: list[tuple[str, str, np.ndarray, np.ndarray]], audio: AudioConfig) -> str:
    b = [f"#define SW_GOLDEN_N_CASES {len(cases)}", ""]
    for k, (name, desc, _x, _lm) in enumerate(cases):
        b.append(f"/* case {k}: {name} - {desc} */")
    b.append("")
    xs = np.stack([c[2] for c in cases])
    lms = np.stack([c[3] for c in cases])
    b.append("/* int16 PCM inputs; float input = x / 32768.0f */")
    b.append(_c_array("int16_t", "sw_golden_input", xs, 16, lambda v: str(int(v))))
    b.append(f"/* reference log-mel (not normalized), [case][frame][mel], frames = {audio.n_frames} */")
    b.append(_c_array("float", "sw_golden_logmel", lms, 8, _fmt_f))
    return _header("SOUNDWATCH_GOLDEN_FEATURES_H", "\n".join(b),
                   "SoundWatch golden feature vectors: compare your C log-mel against these.")


README = """# SoundWatch golden feature vectors

Generated by `python -m soundwatch export-golden`. Use them to verify a C / CMSIS-DSP port of
`soundwatch.audio.features.compute_logmel` (plan section 4.2).

## Feature definition
1. x = int16 / 32768 (float32), 16000 samples.
2. 49 frames of 512 samples, step 320, no padding / centering (frame t = x[320 t : 320 t + 512]).
3. Multiply by the **periodic** Hann window `sw_hann_window` (w[n] = 0.5 - 0.5 cos(2 pi n / 512)).
4. Unscaled real FFT, power = re^2 + im^2 for bins 0..256. CMSIS `arm_rfft_fast_f32` packs bin 256
   (Nyquist) into out[1]: power[0] = out[0]^2, power[256] = out[1]^2.
5. mel[m] = sum over the sparse band (`sw_mel_start/len/offset/weights`, HTK mel, norm=None).
6. logmel = logf(mel + 1e-6) (natural log). Normalization `(logmel - mean) / std` with the scalar
   stats from `feature_stats.json` happens afterwards and is not part of these vectors.

## Files
- `case_<k>_<name>/input.wav` – 16 kHz mono int16 PCM; `input_f32.npy` – exact float32 input;
  `logmel.npy` – (49, 40) float32 reference.
- `golden_features.h` – `sw_golden_input[cases][16000]` (int16), `sw_golden_logmel[cases][49][40]`.
- `mel_filterbank.h` – parameters, Hann window, sparse filterbank (what the firmware uses).
- `manifest.json` – case list and parameters.

## Tolerances (max |C - reference| over all 49 x 40 values of a case)
- float32 C port (FPU, `arm_rfft_fast_f32`): **< 1e-3** expected (typically ~1e-5); the Python
  reference itself agrees with librosa to < 1e-5. Silence must give exactly log(1e-6) = -13.8155.
- Fixed-point port (q15 FFT, no FPU): see `soundwatch.audio.features_fixed`; aim for < 0.1 on
  loud cases. Very quiet inputs lose resolution and are expected to differ more; this is
  acceptable because those windows are below the energy gate (-55 dBFS) and never reach the model.
- Values in the log domain: an error of 1e-3 is a 0.1 % relative error in mel energy.
"""


def export(out: Path, audio: AudioConfig, windows_dir: Path | None = None) -> list[dict]:
    out.mkdir(parents=True, exist_ok=True)
    full = []
    manifest = []
    for k, (name, desc, x) in enumerate(make_cases(audio, windows_dir)):
        d = out / f"case_{k}_{name}"
        d.mkdir(parents=True, exist_ok=True)
        x_f32 = F.to_float32(x)
        lm = F.compute_logmel(x, audio)
        write_wav(d / "input.wav", x, audio.sample_rate)
        np.save(d / "input_f32.npy", x_f32)
        np.save(d / "logmel.npy", lm)
        full.append((name, desc, x, lm))
        manifest.append({"case": k, "name": name, "dir": d.name, "description": desc,
                         "rms_dbfs": round(F.rms_dbfs(x_f32), 3),
                         "logmel_min": float(lm.min()), "logmel_max": float(lm.max())})
    (out / "golden_features.h").write_text(golden_header(full, audio), encoding="utf-8")
    (out / "mel_filterbank.h").write_text(mel_filterbank_header(audio), encoding="utf-8")
    (out / "manifest.json").write_text(
        json.dumps({"params": F.feature_params(audio), "cases": manifest}, indent=2) + "\n", encoding="utf-8")
    (out / "README.md").write_text(README, encoding="utf-8")
    return manifest


def main(args: argparse.Namespace) -> int:
    cfg = load_config(getattr(args, "config", None))
    out = Path(args.out) if getattr(args, "out", None) else paths.GOLDEN
    manifest = export(out, cfg.audio)
    for m in manifest:
        print(f"case {m['case']}: {m['name']:<14} {m['rms_dbfs']:8.2f} dBFS  "
              f"logmel [{m['logmel_min']:.3f}, {m['logmel_max']:.3f}]")
    print(f"wrote {len(manifest)} golden cases + golden_features.h + mel_filterbank.h to {out}")
    return 0
