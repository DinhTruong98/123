"""WP4: export the int8 model + feature parameters + class table as C/C++ sources for TFLite Micro.

  artifacts/firmware/model_data.h / model_data.cc   alignas(16) const unsigned char g_model[]; g_model_len
  artifacts/firmware/feature_params.h               plan 4.2 constants, mean/std, input/output quant
  artifacts/firmware/labels.h                       class keys, labels (ASCII-folded + UTF-8), levels,
                                                    vibration patterns, thresholds, cooldowns, colors
All values come from config/soundwatch.yaml, feature_stats.json and the .tflite file itself.
"""

from __future__ import annotations

import argparse
import unicodedata
from pathlib import Path

from soundwatch import paths
from soundwatch.config import Config, load_config

_HEADER = "// Generated by `python -m soundwatch export` (soundwatch.models.export_c). Do not edit.\n"


def add_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--model", default=None, help="int8 .tflite (default: config model.tflite_path)")
    parser.add_argument("--stats", default=None, help="feature_stats.json (default: config model.stats_path)")
    parser.add_argument("--out", default=None, help="output directory (default: artifacts/firmware)")


def ascii_fold(s: str) -> str:
    """Vietnamese -> plain ASCII for fonts without diacritics (U8g2): 'Báo cháy' -> 'Bao chay'."""
    s = s.replace("đ", "d").replace("Đ", "D")
    s = "".join(ch for ch in unicodedata.normalize("NFD", s) if unicodedata.category(ch) != "Mn")
    return s.encode("ascii", "replace").decode("ascii")


def c_string(s: str) -> str:
    """C string literal; non-ASCII UTF-8 bytes as 3-digit octal escapes (never greedy like \\x)."""
    out = []
    for b in s.encode("utf-8"):
        ch = chr(b)
        if ch in ('"', "\\"):
            out.append("\\" + ch)
        elif 0x20 <= b < 0x7F:
            out.append(ch)
        else:
            out.append(f"\\{b:03o}")
    return '"' + "".join(out) + '"'


def c_ident(s: str) -> str:
    return "".join(ch if ch.isalnum() else "_" for ch in s).upper()


def model_sources(content: bytes, var: str = "g_model") -> tuple[str, str]:
    """(model_data.h, model_data.cc) text for a TFLite flatbuffer."""
    h = (f"{_HEADER}#ifndef SOUNDWATCH_MODEL_DATA_H_\n#define SOUNDWATCH_MODEL_DATA_H_\n\n"
         f"extern const unsigned char {var}[];\nextern const unsigned int {var}_len;\n\n"
         "#endif  // SOUNDWATCH_MODEL_DATA_H_\n")
    rows = []
    for i in range(0, len(content), 12):
        rows.append("  " + ", ".join(f"0x{b:02x}" for b in content[i:i + 12]) + ",")
    cc = (f"{_HEADER}#include \"model_data.h\"\n\n"
          f"// {len(content)} bytes, int8 TFLite flatbuffer (16-byte aligned for TFLite Micro)\n"
          f"alignas(16) const unsigned char {var}[] = {{\n" + "\n".join(rows) + "\n};\n"
          f"const unsigned int {var}_len = {len(content)};\n")
    return h, cc


def _quant_params(content: bytes) -> dict:
    import numpy as np
    import tensorflow as tf

    it = tf.lite.Interpreter(model_content=content)
    inp, out = it.get_input_details()[0], it.get_output_details()[0]
    return {"in_scale": float(inp["quantization"][0]), "in_zp": int(inp["quantization"][1]),
            "out_scale": float(out["quantization"][0]), "out_zp": int(out["quantization"][1]),
            "in_shape": [int(v) for v in inp["shape"]], "out_shape": [int(v) for v in out["shape"]],
            "in_dtype": np.dtype(inp["dtype"]).name, "out_dtype": np.dtype(out["dtype"]).name}


def feature_params_header(cfg: Config, stats: dict, q: dict) -> str:
    a = cfg.audio
    lines = [
        _HEADER, "#ifndef SOUNDWATCH_FEATURE_PARAMS_H_", "#define SOUNDWATCH_FEATURE_PARAMS_H_", "",
        "// Audio front-end (plan section 4.2). logmel = log(mel(|rfft(frame * hann)|^2) + kLogEps)",
        "// Window: periodic Hann w[n] = 0.5 - 0.5*cos(2*pi*n/N); HTK-mel triangular filterbank, no padding.",
        "// Must match soundwatch.audio.features bit-for-bit (check against artifacts/golden/).",
        f"#define SW_SAMPLE_RATE      {a.sample_rate}",
        f"#define SW_WINDOW_SAMPLES   {a.window_samples}",
        f"#define SW_HOP_SAMPLES      {a.hop_samples}",
        f"#define SW_N_FFT            {a.n_fft}",
        f"#define SW_FRAME_LENGTH     {a.n_fft}",
        f"#define SW_FRAME_STEP       {a.frame_step}",
        f"#define SW_N_FRAMES         {a.n_frames}",
        f"#define SW_N_BINS           {a.n_fft // 2 + 1}",
        f"#define SW_N_MELS           {a.n_mels}",
        f"#define SW_FMIN_HZ          {a.fmin:.1f}f",
        f"#define SW_FMAX_HZ          {a.fmax:.1f}f",
        "#define SW_MEL_SCALE_HTK    1",
        f"#define SW_LOG_EPS          {a.log_eps:.9g}f",
        f"#define SW_GATE_DBFS        {a.gate_dbfs:.1f}f",
        "",
        "// Normalization: x = (logmel - mean) / std  (scalars from the train split)",
        f"#define SW_FEATURE_MEAN     {stats['mean']:.9g}f",
        f"#define SW_FEATURE_STD      {stats['std']:.9g}f",
        "",
        f"// Model input {q['in_dtype']} {q['in_shape']}: q = round(x / scale) + zero_point, clamp to int8",
        f"#define SW_INPUT_SCALE      {q['in_scale']:.9g}f",
        f"#define SW_INPUT_ZERO_POINT {q['in_zp']}",
        f"// Model output {q['out_dtype']} {q['out_shape']} = softmax probabilities: p = (q - zp) * scale",
        f"#define SW_OUTPUT_SCALE     {q['out_scale']:.9g}f",
        f"#define SW_OUTPUT_ZERO_POINT {q['out_zp']}",
        "",
        *_frontend_lines(stats),
        "// Post-processing (plan section 4.3)",
        f"#define SW_SMOOTH_N         {cfg.postprocess.smooth_n}",
        f"#define SW_K_OF_N_K         {cfg.postprocess.k_of_n[0]}",
        f"#define SW_K_OF_N_N         {cfg.postprocess.k_of_n[1]}",
        f"#define SW_DANGER_REPEAT_MS {int(round(cfg.postprocess.danger_repeat_s * 1000))}",
        f"#define SW_DANGER_CLEAR_MS  {int(round(cfg.postprocess.danger_clear_s * 1000))}",
        "",
        "#endif  // SOUNDWATCH_FEATURE_PARAMS_H_",
    ]
    return "\n".join(lines) + "\n"


def _frontend_lines(stats: dict) -> list[str]:
    """Extra defines for a non-default model front-end (PCEN, sigmoid output, other window length);
    empty for the historical log-mel / softmax / 1 s models, so their header does not change."""
    from soundwatch.audio.features import model_meta, pcen_smoothing_coef

    meta = model_meta(stats)
    if meta.is_default:
        return []

    def cf(v: float) -> str:  # C float literal (always with '.' or exponent: "2f" is not valid C)
        t = f"{float(v):.9g}"
        return (t if any(ch in t for ch in ".e") else t + ".0") + "f"

    p = stats.get("params", {})
    sr, step = int(p.get("sample_rate", 16000)), int(p.get("frame_step", 320))
    out = ["// Model front-end (feature_stats.json params, vn-v2)",
           f"#define SW_FRONTEND_PCEN    {1 if meta.frontend == 'pcen' else 0}",
           f"#define SW_OUTPUT_SIGMOID   {1 if meta.output == 'sigmoid' else 0}"]
    if meta.window_s is not None:
        out.append(f"#define SW_MODEL_WINDOW_SAMPLES {int(round(meta.window_s * sr))}")
    if meta.output == "sigmoid":
        out.append("// Sigmoid output: independent per-class probabilities (no softmax; need not sum to 1)")
    if meta.frontend == "pcen":
        pc = meta.pcen_params
        out += [
            "// PCEN replaces logmel (stateless per window, smoother initialised with the first frame):",
            "//   M[0] = E[0]; M[t] = (1 - S) * M[t-1] + S * E[t]   (E = mel power, per mel band)",
            "//   pcen = powf(E / powf(EPS + M, GAIN) + BIAS, POWER) - powf(BIAS, POWER)",
            "// then x = (pcen - SW_FEATURE_MEAN) / SW_FEATURE_STD.",
            f"#define SW_PCEN_S           {cf(pcen_smoothing_coef(pc['time_constant_s'], sr, step))}",
            f"#define SW_PCEN_GAIN        {cf(pc['gain'])}",
            f"#define SW_PCEN_BIAS        {cf(pc['bias'])}",
            f"#define SW_PCEN_POWER       {cf(pc['power'])}",
            f"#define SW_PCEN_EPS         {cf(pc['eps'])}",
            f"// time constant {pc['time_constant_s']:g} s",
        ]
    return out + [""]


def _modes_lines(cfg: Config) -> list[str]:
    """Context modes (config `modes:`) as per-mode tables; empty when the config has none."""
    m = cfg.modes
    if m is None:
        return []
    cls = cfg.classes
    names = [n for n, _ in m.modes]
    out = ["// Context modes (config `modes:`). Mode i: class c off if kModeDisabled[i][c],",
           "// level = kModeLevel[i][c] (overrides kClassLevel).",
           f"#define SW_NUM_MODES {len(names)}"]
    for i, n in enumerate(names):
        out.append(f"#define SW_MODE_{c_ident(n)} {i}")
    default = m.default
    out.append(f"#define SW_MODE_DEFAULT_AUTO {1 if default == 'auto' else 0}")
    if default != "auto":
        out.append(f"#define SW_MODE_DEFAULT SW_MODE_{c_ident(default)}")
    out.append("static const char* const kModeNames[SW_NUM_MODES] = {"
               + ", ".join(c_string(n) for n in names) + "};")
    dis, lev = [], []
    for _, spec in m.modes:
        lm = spec.level_map
        dis.append("{" + ", ".join("1" if c.key in spec.disable else "0" for c in cls) + "}")
        lev.append("{" + ", ".join(str(int(lm.get(c.key, int(c.level)))) for c in cls) + "}")
    out.append("static const uint8_t kModeDisabled[SW_NUM_MODES][SW_NUM_CLASSES] = {\n  "
               + ",\n  ".join(dis) + "};")
    out.append("static const uint8_t kModeLevel[SW_NUM_MODES][SW_NUM_CLASSES] = {\n  "
               + ",\n  ".join(lev) + "};")
    if m.auto is not None:
        a = m.auto
        out += ["// auto: street while the running median of the per-hop RMS over the window is above",
                f"#define SW_AUTO_STREET_ABOVE_DBFS {a.street_above_dbfs:.1f}f",
                f"#define SW_AUTO_WINDOW_MS   {int(round(a.window_s * 1000))}",
                f"#define SW_AUTO_HYSTERESIS_DB {a.hysteresis_db:.1f}f",
                f"#define SW_AUTO_MIN_MS      {int(round(a.min_s * 1000))}"]
    return out + [""]


def labels_header(cfg: Config) -> str:
    cls = cfg.classes
    n = len(cls)
    vib_flat: list[int] = []
    offsets: list[int] = []
    for c in cls:
        offsets.append(len(vib_flat))
        vib_flat.extend(c.vibration)

    def arr(ctype: str, name: str, vals: list[str]) -> str:
        return f"static const {ctype} {name}[SW_NUM_CLASSES] = {{\n" + "".join(
            f"  {v},  // {c.key}\n" for v, c in zip(vals, cls, strict=True)) + "};\n"

    out = [_HEADER, "#ifndef SOUNDWATCH_LABELS_H_", "#define SOUNDWATCH_LABELS_H_", "",
           "#include <stdint.h>", "",
           f"#define SW_NUM_CLASSES {n}", f"#define SW_BACKGROUND_ID {cfg.background_id}", "",
           "enum sw_level_t { SW_LEVEL_INFO = 0, SW_LEVEL_WARN = 1, SW_LEVEL_DANGER = 2 };", "",
           "enum sw_class_id_t {"]
    out += [f"  SW_CLASS_{c_ident(c.key)} = {c.id}," for c in cls]
    out += ["};", ""]
    out.append(arr("char* const", "kClassKeys", [c_string(c.key) for c in cls]))
    out.append("// Labels without diacritics, for fonts lacking Vietnamese glyphs (e.g. U8g2 built-ins)")
    out.append(arr("char* const", "kLabelsAscii", [c_string(ascii_fold(c.label_vi)) for c in cls]))
    out.append("// Vietnamese labels, UTF-8 (U8g2 drawUTF8 / LVGL)")
    out.append(arr("char* const", "kLabelsUtf8", [c_string(c.label_vi) for c in cls]))
    out.append(arr("uint8_t", "kClassLevel", [f"SW_LEVEL_{c.level.name}" for c in cls]))
    out.append(arr("uint8_t", "kClassEnabledDefault", ["1" if c.enabled else "0" for c in cls]))
    out.append("// Smoothed-probability alert thresholds, scaled by 1000 and as float")
    out.append(arr("uint16_t", "kThresholdPermille", [str(int(round(c.threshold * 1000))) for c in cls]))
    out.append(arr("float", "kThreshold", [f"{c.threshold:.4f}f" for c in cls]))
    out.append(arr("uint32_t", "kCooldownMs", [str(int(round(c.cooldown_s * 1000))) for c in cls]))
    out.append("// Alert color RGB888 (0xRRGGBB) and RGB565")
    out.append(arr("uint32_t", "kColorRgb888",
                   [f"0x{c.color[0]:02X}{c.color[1]:02X}{c.color[2]:02X}" for c in cls]))
    out.append(arr("uint16_t", "kColorRgb565", [
        f"0x{((c.color[0] >> 3) << 11) | ((c.color[1] >> 2) << 5) | (c.color[2] >> 3):04X}" for c in cls]))
    out.append(arr("char* const", "kIconName", [c_string(c.icon) for c in cls]))
    out.append("// Vibration patterns: on/off durations (ms) alternating, starting with on.")
    out.append("// Pattern of class i = kVibration[kVibrationOffset[i] .. + kVibrationLen[i]]")
    body = ", ".join(str(v) for v in vib_flat) if vib_flat else "0"
    out.append(f"static const uint16_t kVibration[{max(1, len(vib_flat))}] = {{{body}}};")
    out.append(arr("uint16_t", "kVibrationOffset", [str(o) for o in offsets]))
    out.append(arr("uint8_t", "kVibrationLen", [str(len(c.vibration)) for c in cls]))
    for c in cls:
        if c.vibration:
            out.append(f"static const uint16_t kVib_{c.key}[{len(c.vibration)}] = "
                       f"{{{', '.join(str(v) for v in c.vibration)}}};")
    modes = _modes_lines(cfg)
    if modes:
        out += [""] + modes
    out += ["", "#endif  // SOUNDWATCH_LABELS_H_"]
    return "\n".join(out) + "\n"


def export_all(cfg: Config, model_path: Path, stats_path: Path, out_dir: Path) -> dict[str, Path]:
    from soundwatch.audio.features import load_stats

    content = Path(model_path).read_bytes()
    stats = load_stats(stats_path)
    out_dir.mkdir(parents=True, exist_ok=True)
    h, cc = model_sources(content)
    files = {
        "model_data.h": h,
        "model_data.cc": cc,
        "feature_params.h": feature_params_header(cfg, stats, _quant_params(content)),
        "labels.h": labels_header(cfg),
    }
    written = {}
    for name, text in files.items():
        p = out_dir / name
        p.write_text(text, encoding="utf-8")
        written[name] = p
    return written


def main(args: argparse.Namespace) -> int:
    cfg = load_config(args.config)
    model = Path(args.model) if args.model else cfg.model.resolved_tflite()
    stats = Path(args.stats) if args.stats else cfg.model.resolved_stats()
    out = Path(args.out) if args.out else paths.FIRMWARE
    if not model.exists():
        raise FileNotFoundError(f"{model} not found (run `quantize` first)")
    written = export_all(cfg, model, stats, out)
    for p in written.values():
        print(f"[export] {p} ({p.stat().st_size / 1024:.1f} KB)")
    return 0
